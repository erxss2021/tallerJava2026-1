package ciclos;

public class CicloFor {
    public static void main(String[] args) {
        System.out.println("----Mostrar los numeros del 10 al 1----");
        
        for(int i = 10; i >= 1; i--){
            System.out.print(i + " ");
        }
        // System.out.println("\ni: " + i);

    }
}
